#!/usr/bin/env bash
# Both transports, normalized inventory, fail-closed detection and lifecycle.
. "$(dirname "$0")/lib.sh"
H=$BIN_DIR/herdr-backend.sh
assert_eq tui-marker tui "$("$H" flavor)"
HC_TERMINAL_ID=t1 "$H" flavor >"$SCRATCH/detected"
assert_eq both-tui tui "$(cat "$SCRATCH/detected")"
HC_TERMINAL_ID=t1 HERDR_FLAVOR=app "$H" flavor >"$SCRATCH/detected"
assert_eq override-present app "$(cat "$SCRATCH/detected")"
HERDR_ENV='' "$H" flavor >/dev/null 2>&1; assert_eq neither 1 "$?"
HERDR_FLAVOR=app "$H" flavor >/dev/null 2>&1; assert_eq override-missing-app 1 "$?"
HERDR_ENV='' HC_TERMINAL_ID=t1 HERDR_FLAVOR=tui "$H" flavor >/dev/null 2>&1; assert_eq override-missing-tui 1 "$?"
assert_eq detection-no-calls '' "$(cat "$MOCK_LOG")"
mkdir "$SCRATCH/run"
echo '{"herdr":{"flavor":"app"}}' >"$SCRATCH/run/status.json"
"$H" flavor "$SCRATCH/run" >/dev/null 2>&1; assert_eq mismatch 1 "$?"
HERDR_BACKEND_RUN_DIR=$SCRATCH/run "$H" agents >/dev/null 2>&1; assert_eq implicit-mismatch 1 "$?"
export HERDR_PANE_ID=w1:p1 HERDR_TAB_ID=w1:t1 HERDR_WORKSPACE_ID=w1
assert_eq tui-self '{"flavor":"tui","id":"w1:p1","pane":"w1:p1","tab":"w1:t1","space":"w1"}' "$("$H" self)"
echo '{"result":{"agents":[{"name":"worker","pane_id":"w1:p2","tab_id":"w1:t1","workspace_id":"w1","agent":"fixture","agent_status":"idle","status_age_s":4,"terminal_title_stripped":"Title"}]}}' >"$HERDR_SCENARIO/agents.json"
echo '{"result":{"tabs":[{"tab_id":"w1:t1","workspace_id":"w1","label":"Tab"}]}}' >"$HERDR_SCENARIO/tabs.json"
echo '{"result":{"workspaces":[{"workspace_id":"w1","label":"Space"}]}}' >"$HERDR_SCENARIO/workspaces.json"
echo '{"result":{"panes":[{"pane_id":"w1:p2","tab_id":"w1:t1","workspace_id":"w1","agent":"fixture","agent_status":"idle","cwd":"/tmp"}]}}' >"$HERDR_SCENARIO/panes.json"
echo '{"result":{"layout":{"focused_pane_id":"w1:p1","panes":[{"pane_id":"w1:p1","rect":{"width":114,"height":31}}]}}}' >"$HERDR_SCENARIO/layout.json"
assert_eq tui-agent 'worker|w1:p2|w1:p2|w1:t1|w1|fixture|idle|4|Title' "$("$H" agents | jq -r '.[0]|[.name,.id,.pane,.tab,.space,.kind,.status,.status_age_s,.title]|join("|")')"
assert_eq tui-tabs '[{"id":"w1:t1","label":"Tab","space":"w1"}]' "$("$H" tabs)"
assert_eq tui-spaces '[{"id":"w1","label":"Space"}]' "$("$H" spaces)"
assert_eq tui-panes w1:p2 "$("$H" panes | jq -r '.[0].id')"
assert_eq tui-prefixes '[]' "$("$H" prefixes)"
assert_eq tui-geometry '114 31' "$("$H" geometry)"
"$H" rename-self new-overseer; assert_eq tui-rename-exit 0 "$?"
"$H" rename-tab w1:t1 Label; "$H" rename-space w1 Space
assert_eq tui-tab-new 'tab=w1:tnew pane=w1:pnew' "$("$H" tab-new w1 Label "$SCRATCH")"
echo '{"prefix":"fixture","agents":[],"herdr":{}}' >"$SCRATCH/run/status.json"
assert_eq tui-board w1:pboard "$("$H" open-board "$SCRATCH/run" 0.65)"
assert_eq tui-start w1:p2 "$("$H" start worker fixture "$SCRATCH" --pane w1:p2 --timeout 2 -- --pin 'two words')"
assert_contains tui-start-timeout 'herdr agent start worker --kind fixture --pane w1:p2 --timeout 2000 -- --pin two words' "$(cat "$MOCK_LOG")"
assert_eq tui-prompt started=true "$("$H" prompt worker text)"
assert_eq tui-wait done "$("$H" wait worker 2)"
printf 'one\ntwo\nthree\n' >"$HERDR_SCENARIO/pane.txt"
assert_eq tui-tail $'two\nthree' "$("$H" read-tail worker 2)"
"$H" keys worker esc ctrl-c; "$H" close w1:p2
assert_contains tui-keys 'herdr agent send-keys worker esc ctrl-c' "$(cat "$MOCK_LOG")"
assert_contains tui-close 'herdr pane close w1:p2' "$(cat "$MOCK_LOG")"
assert_eq tui-callback 'herdr agent prompt fixture-overseer "<message>"' "$("$H" callback-line fixture)"
echo '{"result":{"agents":[]}}' >"$HERDR_SCENARIO/agents.json"
jq -n --arg cwd "$(cd "$SCRATCH" && pwd -P)" '{result:{pane:{foreground_cwd:$cwd}}}' >"$HERDR_SCENARIO/pane-get.json"
assert_eq tui-rotate w1:p2 "$("$H" rotate worker w1:p2 "$SCRATCH" fixture -- --pin fixed | jq -r .result.agent.pane_id)"
"$H" unsupported >/dev/null 2>&1; assert_eq tui-unsupported 3 "$?"
"$H" keys >/dev/null 2>&1; assert_eq tui-usage 2 "$?"

app_fixture
assert_eq app-marker app "$("$H" flavor)"
assert_eq app-self '{"flavor":"app","id":"t1","pane":"pa1","tab":"tb1","space":"sp1"}' "$("$H" self)"
assert_eq app-missing-self '{"flavor":"app","id":"hidden","pane":null,"tab":null,"space":null}' "$(HC_TERMINAL_ID=hidden "$H" self)"
assert_eq app-agent-null-name null "$("$H" agents | jq -r '.[0].name')"
assert_eq app-agent-status idle "$("$H" agents | jq -r '.[0].status')"
assert_eq app-age-null null "$("$H" agents | jq -r '.[0].status_age_s')"
assert_eq app-tabs '[{"id":"tb1","label":"old tab","space":"sp1"}]' "$("$H" tabs)"
assert_eq app-spaces '[{"id":"sp1","label":"old space"}]' "$("$H" spaces)"
assert_eq app-panes 'pa1|tb1|sp1|t1|fixture|idle' "$("$H" panes | jq -r '.[0]|[.id,.tab,.space,.terminal,.agent,.status]|join("|")')"
assert_eq app-geometry '114 31' "$("$H" geometry)"
"$H" rename-self fixture-overseer
assert_eq app-prefixes '["fixture"]' "$("$H" prefixes)"
assert_contains app-labels 'hc label t1 run.name=fixture-overseer run.prefix=fixture run.role=overseer' "$(cat "$MOCK_LOG")"
"$H" rename-tab tb1 Label; "$H" rename-space sp1 Space
assert_eq app-renamed-tab Label "$("$H" tabs | jq -r '.[0].label')"
assert_eq app-renamed-space Space "$("$H" spaces | jq -r '.[0].label')"
assert_eq app-tab-new 'tab=tbnew1 pane=proottbnew1' "$("$H" tab-new sp1 'fixture·N1' "$SCRATCH")"
assert_eq app-root-default unknown "$("$H" geometry proottbnew1)"
jq '.[1].foreground={name:"zsh",argv:["/bin/zsh","-l"]}' "$HC_SCENARIO/terminals.json" >"$SCRATCH/core"
mv "$SCRATCH/core" "$HC_SCENARIO/terminals.json"
assert_eq app-start tnew1 "$("$H" start fixture-impl tool "$SCRATCH" --pane proottbnew1 --timeout 2 -- --pin 'two words')"
assert_contains app-command 'hc run --bg --name fixture-impl --cwd' "$(cat "$MOCK_LOG")"
assert_contains app-native-args '-- tool --pin two words' "$(cat "$MOCK_LOG")"
assert_contains app-root-removed 'hc rm roottbnew1' "$(cat "$MOCK_LOG")"
assert_eq app-default-geometry unknown "$("$H" geometry ptnew1)"
assert_eq sole-adopted-pane 1 "$("$H" panes | jq '[.[]|select(.tab=="tbnew1")]|length')"
assert_eq app-second-start tnew2 "$("$H" start fixture-review tool "$SCRATCH" --tab tbnew1 --space sp1 --timeout 2 --)"
assert_eq app-no-agent-root-disposal 1 "$(grep -c '^hc kill roottbnew1$' "$MOCK_LOG")"
assert_eq app-prompt started=true "$("$H" prompt fixture-impl text)"
echo '{"started":false,"status":"idle","turn":0}' >"$HC_SCENARIO/send.json"
assert_eq app-prompt-false started=false "$("$H" prompt fixture-impl text)"
echo '{"started":null,"status":null,"turn":0}' >"$HC_SCENARIO/send.json"
assert_eq app-prompt-null started=null "$("$H" prompt fixture-impl text)"
assert_eq app-wait idle "$("$H" wait fixture-impl 2)"
assert_eq app-read-bound '   ' "$("$H" read-tail fixture-impl 1)"
assert_contains app-read-screen-only 'hc read fixture-impl --lines 0 --json' "$(cat "$MOCK_LOG")"
"$H" keys fixture-impl ctrl-c esc
assert_contains app-key-normalization 'hc keys fixture-impl ctrl+c esc' "$(cat "$MOCK_LOG")"
assert_eq app-board pboard "$("$H" open-board "$SCRATCH/run" 0.7)"
assert_contains app-board-argv 'herdr-app do pane.split --direction down --pane pa1 --argv [' "$(cat "$MOCK_LOG")"
assert_contains app-callback 'end your turn' "$("$H" callback-line fixture)"
assert_eq app-rotate tnew3 "$("$H" rotate fixture-impl ptnew1 "$SCRATCH" tool -- --pin same)"
assert_contains app-rotate-labels '--label herdr.space=sp1 --label herdr.tab=tbnew1 -- tool --pin same' "$(cat "$MOCK_LOG")"
"$H" close fixture-review
assert_contains app-close-kill 'hc kill tnew2' "$(cat "$MOCK_LOG")"
assert_contains app-close-rm 'hc rm tnew2' "$(cat "$MOCK_LOG")"
# Missing native OSC state is never fabricated from the ls status.
jq '.[0].status=null|.[0].reported=false' "$HC_SCENARIO/terminals.json" >"$SCRATCH/core"
mv "$SCRATCH/core" "$HC_SCENARIO/terminals.json"
assert_eq silent-status null "$("$H" agents | jq -r '.[0].status')"
echo null >"$HC_SCENARIO/run-status.json"
out=$("$H" start silent tool "$SCRATCH" --tab tb1 --timeout 1 -- 2>&1)
assert_eq silent-never-ready 1 "$?"
assert_contains silent-reason 'readiness timed out' "$out"
echo '{"app":"fixture","state":"blocked"}' >"$HC_SCENARIO/run-status.json"
out=$("$H" start blocked tool "$SCRATCH" --tab tb1 --timeout 1 -- 2>&1)
assert_eq blocked-never-ready 1 "$?"
assert_contains blocked-reason 'not ready: blocked' "$out"
echo '{"app":"fixture","state":"done"}' >"$HC_SCENARIO/run-status.json"
assert_eq done-ready tnew6 "$("$H" start done tool "$SCRATCH" --tab tb1 --timeout 1 --)"
touch "$HC_SCENARIO/no-adoption"
out=$("$H" start hidden tool "$SCRATCH" --tab tb1 --timeout 1 -- 2>&1)
assert_eq adoption-required 1 "$?"
assert_contains adoption-reason 'not adopted into tab' "$out"
"$H" unsupported >/dev/null 2>&1; assert_eq app-unsupported 3 "$?"
"$H" start bad tool "$SCRATCH" --pane pa1 --tab tb1 -- >/dev/null 2>&1; assert_eq app-start-usage 2 "$?"
# A shell with a foreground command must remain visible.
app_fixture
"$H" tab-new sp1 'fixture·busy' "$SCRATCH" >/dev/null
jq '.[1].foreground={name:"python3",argv:["python3","job.py"]}' "$HC_SCENARIO/terminals.json" >"$SCRATCH/core"
mv "$SCRATCH/core" "$HC_SCENARIO/terminals.json"
assert_eq busy-root-start tnew1 "$("$H" start busy tool "$SCRATCH" --tab tbnew1 --space sp1 --timeout 2 --)"
assert_eq busy-root-not-killed 0 "$(grep -c '^hc kill roottbnew1$' "$MOCK_LOG")"
app_fixture
echo null >"$HC_SCENARIO/run-status.json"
echo '{"app":"fixture","state":"idle"}' >"$HC_SCENARIO/wait-promote.json"
touch "$HC_SCENARIO/delay-adoption"
assert_eq waits-for-reported-status tnew1 "$("$H" start delayed tool "$SCRATCH" --tab tb1 --timeout 3 --)"
assert_contains readiness-wait 'hc wait tnew1 --timeout' "$(cat "$MOCK_LOG")"
assert_eq adopted-after-delay tb1 "$("$H" agents | jq -r '.[]|select(.id=="tnew1")|.tab')"
# Blank or malformed CLI responses fail without falling through to a real command.
echo 1 >"$HC_SCENARIO/get.exit"
"$H" agents >/dev/null 2>&1; assert_eq app-get-failure 1 "$?"
rm "$HC_SCENARIO/get.exit"
echo '{}' >"$HC_SCENARIO/ls.response.json"
"$H" prefixes >/dev/null 2>&1; assert_eq app-malformed-ls 1 "$?"
finish
